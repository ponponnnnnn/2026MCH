/**
 * 長輩按下通話按鈕後，送給模型的第一句話，觸發上面兩套開場規則的第一步。
 * 這不是規則本身，只是「現在開始」的信號，所以放在同一個檔案，由 call/live.ts 呼叫。
 * 首次通話用登記姓名（elderName）稱呼「後台登記的名字」；例行通話一律只觸發第 1 步（不帶問句），
 * 不能寫「開始聊天」這類會讓模型把問候、提問一次講完的措辭。
 */
export function buildKickoff(briefing: Briefing): string {
  if (briefing.isFirstCall) {
    const identityNote =
      briefing.elderName && briefing.elderName !== "長輩"
        ? `${briefing.elderName}是後台登記的名字，稱呼要問他本人，不要直接拿來叫。`
        : "";
    return `（長輩剛按下通話按鈕，這是你們的第一次通話。請照首次通話的開場順序先開口。${identityNote}）`.trim();
  }
  const who = briefing.preferredName ?? briefing.knownFacts.preferredName ?? "長輩";
  return `（${who}剛按下通話按鈕。請照例行通話開場的第 1 步先開口：只報身分和問候，不帶問句，然後等他回應）`;
}
